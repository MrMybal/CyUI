"""Regenerate CyUI's embedded default code font from its pinned, unmodified asset."""
from pathlib import Path
import hashlib
import json
import sys

ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'third_party/jetbrains-mono'
lock=json.loads((source/'VERSION.json').read_text('utf-8'))
for name,digest in lock['files'].items():
    if hashlib.sha256((source/name).read_bytes()).hexdigest()!=digest:
        raise SystemExit(f'Pinned font differs: {name}')
font=(source/'JetBrainsMono-Regular.ttf').read_bytes()
text='// Generated by tools/embed_code_font.py; do not edit.\n// Copyright 2020 The JetBrains Mono Project Authors; SIL OFL 1.1.\n// See third_party/jetbrains-mono/OFL.txt. Original font bytes, unmodified.\nstatic const unsigned char jetBrainsMonoRegular[] = {\n'
text+=''.join('    '+','.join(f'0x{b:02x}' for b in font[n:n+20])+',\n' for n in range(0,len(font),20))+'};\n'
outputs={ROOT/'src/fonts/JetBrainsMonoRegular.inc':text.encode('utf-8'),
         ROOT/'python/cyui_modules/fonts/JetBrainsMono-Regular.ttf':font,
         ROOT/'python/cyui_modules/fonts/OFL.txt':(source/'OFL.txt').read_bytes()}
for path,data in outputs.items():
    if '--check' in sys.argv:
        if not path.is_file() or path.read_bytes()!=data: raise SystemExit(f'Stale font output: {path}')
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_bytes(data)
print('Embedded font, Python asset and OFL notice match the pinned source.')
